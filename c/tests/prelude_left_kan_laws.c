/* required_rows(names, rows) */
static Task required_rows(Heap *heap, const Vec *names, const Vec *rows) {
  for (size_t i = 0; i < names->len; i++) {
    Str name = at_str(names, i);
    RELATIONAL_TRY(relational_require(relational_contains(rows, name),
                                      cat(heap, str_lit("missing checked law or symbolic pin: "), name)));
  }
  return task_pure();
}

/* suite(root) */
static Task suite(Heap *heap, void *ctx, Str *fields) {
  Str root = *(const Str *)ctx;
  Str templates = str_empty();
  Vec template_paths = STRINGS(heap, TEMPLATE_PATHS);
  Str fixture = str_empty();
  Vec fixture_paths = vec_new(heap->arena);
  const Vec *parsed = NULL;
  const ElabChecked *checked = NULL;
  Vec entries = vec_new(heap->arena);
  Vec families;
  Globals globals;
  Vec pins;
  Vec equality;
  Vec rows = vec_new(heap->arena);
  Vec negatives = vec_new(heap->arena);
  RELATIONAL_TRY(relational_read_all(heap, root, &template_paths, &templates));
  RELATIONAL_TRY(relational_read_all(heap, root, &fixture_paths, &fixture));
  RELATIONAL_TRY(relational_parse_roundtrip(heap, cat(heap, cat(heap, templates, str_lit("\n")), fixture), &parsed));
  RELATIONAL_TRY(relational_elaborated(heap, global_initial(heap), parsed, &checked));
  PUSH_STRINGS(heap, &entries, EXPECTED_ENTRIES);
  PUSH_STRINGS(heap, &entries, EQUALITY_ENTRIES);
  PUSH_STRINGS(heap, &entries, ACTION_ENTRIES);
  PUSH_STRINGS(heap, &entries, ROUNDTRIP_ENTRIES);
  PUSH_STRINGS(heap, &entries, MEDIATOR_EQUALITY_ENTRIES);
  PUSH_STRINGS(heap, &entries, SOLUTION_TRANSPORT_ENTRIES);
  families = STRINGS(heap, EXPECTED_FAMILIES);
  RELATIONAL_TRY(program_inventory(heap, checked, &entries, &families));
  globals = relational_globals(checked);
  pins = STRINGS(heap, REQUIRED_PINS);
  {
    Vec names = relational_entry_names(heap, relational_rows(checked));
    RELATIONAL_TRY(required_rows(heap, &pins, &names));
  }
  equality = STRINGS(heap, EQUALITY_ENTRIES);
  {
    Vec names = relational_entry_names(heap, relational_rows(checked));
    RELATIONAL_TRY(required_rows(heap, &equality, &names));
  }
  values(heap, &rows);
  equality_values(heap, &rows);
  RELATIONAL_TRY(relational_computations(heap, &rows, globals));
  PUSH_STRINGS(heap, &negatives, NEGATIVES);
  PUSH_STRINGS(heap, &negatives, EQUALITY_NEGATIVES);
  RELATIONAL_TRY(negatives_run(heap, root, str_lit("test/neg/left-kan-laws"), &negatives, globals,
                               negatives_prefix(64, true, false)));
  *fields = str_lit("entries=1045 families=9 computations=26 negatives=23");
  return task_pure();
}

/* equality_checked(root): R.kernel(Elab.check_in(G.initial(), Budget.unlimited(), source)) is R.checked. */
static Task equality_checked(Heap *heap, Str root, const ElabChecked **checked) {
  Str source = str_empty();
  Vec equality;
  Vec axioms;
  Vec none = vec_new(heap->arena);
  RELATIONAL_TRY(relational_read(heap, root, str_lit("_bend2/left-kan-cocone-equality-contracts/focused-source.mech"),
                                 &source));
  RELATIONAL_TRY(relational_checked(heap, global_initial(heap), source, checked));
  equality = STRINGS(heap, EQUALITY_ENTRIES);
  {
    Vec names = relational_entry_names(heap, relational_rows(*checked));
    RELATIONAL_TRY(required_rows(heap, &equality, &names));
  }
  axioms = elab_axiom_names(heap, relational_rows(*checked));
  RELATIONAL_TRY(relational_require(relational_strings(&axioms, &none), str_lit("cocone equality introduced an axiom")));
  return task_pure();
}

/* equality_suite(root) */
static Task equality_suite(Heap *heap, void *ctx, Str *fields) {
  Str root = *(const Str *)ctx;
  const ElabChecked *checked = NULL;
  Globals globals;
  Vec rows = vec_new(heap->arena);
  Vec negatives;
  RELATIONAL_TRY(equality_checked(heap, root, &checked));
  globals = relational_globals(checked);
  equality_values(heap, &rows);
  RELATIONAL_TRY(relational_computations(heap, &rows, globals));
  negatives = STRINGS(heap, EQUALITY_NEGATIVES);
  RELATIONAL_TRY(negatives_run(heap, root, str_lit("test/neg/left-kan-laws"), &negatives, globals,
                               negatives_prefix(64, true, false)));
  *fields = str_lit("laws=3 contracts=3 computations=6 negatives=5");
  return task_pure();
}

/* equality_oracles(root, names, globals): name ++ "\t" ++ message ++ "\n" per name, in order. */
static Task equality_oracles(Heap *heap, Str root, const Vec *names, Globals globals, Str *text) {
  Str out = str_empty();
  for (size_t i = 0; i < names->len; i++) {
    Str name = at_str(names, i);
    Str source = str_empty();
    Str message = str_empty();
    RELATIONAL_TRY(relational_read(heap, root, cat(heap, cat(heap, str_lit("test/neg/left-kan-laws/"), name),
                                                   str_lit(".mech")), &source));
    RELATIONAL_TRY(negatives_message(heap, elab_check_in(heap, globals, budget_unlimited(), source), name, &message));
    out = cat(heap, out, cat(heap, cat(heap, cat(heap, name, str_lit("\t")), message), str_lit("\n")));
  }
  *text = out;
  return task_pure();
}

/* equality_record(root) */
static Task equality_record(Heap *heap, void *ctx, Str *fields) {
  Str root = *(const Str *)ctx;
  const ElabChecked *checked = NULL;
  Vec negatives;
  RELATIONAL_TRY(equality_checked(heap, root, &checked));
  negatives = STRINGS(heap, EQUALITY_NEGATIVES);
  return equality_oracles(heap, root, &negatives, relational_globals(checked), fields);
}

/* selected(equality, record, root) */
static int selected(Heap *heap, bool equality, bool record, Str *root) {
  if (equality) return relational_run(heap, str_lit("PRELUDE-LEFT-KAN-COCONE-EQUALITY"), equality_suite, root);
  if (record) return relational_run(heap, str_lit("COCONE-EQUALITY-ORACLES"), equality_record, root);
  return driver_die(64, "expected ROOT [--cocone-equality|--record-cocone-equality-oracles]");
}

/* arguments(args): exactly ROOT FLAG selects a focused mode; anything else runs suite(R.root(args)). */
static int arguments(Heap *heap, int argc, char **argv) {
  Str root = relational_root(argc, argv);
  if (argc == 3) {
    Str flag = str_lit(argv[2]);
    return selected(heap, str_eq(flag, str_lit("--cocone-equality")),
                    str_eq(flag, str_lit("--record-cocone-equality-oracles")), &root);
  }
  return relational_run(heap, str_lit("PRELUDE-LEFT-KAN-LAWS"), suite, &root);
}

static int program(int argc, char **argv) {
  Arena arena = arena_new(1 << 20);
  Heap heap = heap_new(&arena);
  int code = arguments(&heap, argc, argv);
  if (heap.oom) code = driver_host_failure();
  arena_free(&arena);
  return code;
}

int main(int argc, char **argv) { return rt_run_main(argc, argv, program); }
